import 'package:intl/intl.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';

import '../maintenance/models/service_record.dart';
import '../vehicles/models/vehicle.dart';

/// Generates a service-history PDF and opens the share/print sheet. Useful for
/// resale ("full service history") and warranty claims.
abstract class ServiceHistoryPdf {
  static Future<void> export(
      Vehicle vehicle, List<ServiceRecord> history) async {
    final df = DateFormat.yMMMd();
    final doc = pw.Document();

    doc.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        build: (context) => [
          pw.Header(
            level: 0,
            child: pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                pw.Text('Siyyarte — Service History',
                    style: pw.TextStyle(
                        fontSize: 22, fontWeight: pw.FontWeight.bold)),
                pw.SizedBox(height: 4),
                pw.Text(vehicle.displayName,
                    style: const pw.TextStyle(fontSize: 14)),
                if (vehicle.plateNumber != null)
                  pw.Text('Plate: ${vehicle.plateNumber}',
                      style: const pw.TextStyle(fontSize: 11)),
                pw.Text(
                    'Current odometer: ${NumberFormat.decimalPattern().format(vehicle.odometerKm)} km',
                    style: const pw.TextStyle(fontSize: 11)),
              ],
            ),
          ),
          pw.SizedBox(height: 12),
          pw.TableHelper.fromTextArray(
            headerStyle: pw.TextStyle(fontWeight: pw.FontWeight.bold),
            headerDecoration:
                const pw.BoxDecoration(color: PdfColors.grey300),
            cellAlignment: pw.Alignment.centerLeft,
            headers: const [
              'Date',
              'Service',
              'Odometer (km)',
              'Garage',
              'Cost',
              'Notes'
            ],
            data: history
                .map((r) => [
                      df.format(r.date),
                      r.type.name,
                      NumberFormat.decimalPattern().format(r.odometerKm),
                      r.garageName ?? '-',
                      r.cost?.formatted() ?? '-',
                      r.notes ?? '-',
                    ])
                .toList(),
          ),
          pw.SizedBox(height: 16),
          pw.Text(
            'All cost figures are as recorded by the owner. Generated by Siyyarte. '
            'Maintenance intervals follow manufacturer factory schedules.',
            style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey600),
          ),
        ],
      ),
    );

    await Printing.layoutPdf(onLayout: (format) => doc.save());
  }
}
