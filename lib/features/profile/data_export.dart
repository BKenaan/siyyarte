import 'package:intl/intl.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';

import '../../core/constants/lebanon.dart';
import '../auth/models/app_user.dart';
import '../maintenance/models/service_record.dart';
import '../vehicles/models/vehicle.dart';

typedef VehicleWithHistory = ({Vehicle vehicle, List<ServiceRecord> history});

/// Exports the user's full data set (profile + vehicles + service history) as a
/// PDF — the user-facing "export my data" required by Apple/Google policies.
abstract class AccountDataPdf {
  static Future<void> export(
      AppUser user, List<VehicleWithHistory> data) async {
    final df = DateFormat.yMMMd();
    final doc = pw.Document();

    doc.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        build: (context) => [
          pw.Header(
            level: 0,
            child: pw.Text('Siyyarte — My Data Export',
                style:
                    pw.TextStyle(fontSize: 22, fontWeight: pw.FontWeight.bold)),
          ),
          pw.Text('Profile',
              style: pw.TextStyle(fontSize: 15, fontWeight: pw.FontWeight.bold)),
          pw.SizedBox(height: 6),
          pw.Bullet(text: 'Name: ${user.name ?? '-'}'),
          if (user.email != null) pw.Bullet(text: 'Email: ${user.email}'),
          if (user.phone != null) pw.Bullet(text: 'Phone: ${user.phone}'),
          if (user.city != null) pw.Bullet(text: 'City: ${user.city}'),
          pw.Bullet(text: 'Language: ${user.language}'),
          pw.Bullet(text: 'Currency: ${user.preferredCurrency.code}'),
          pw.SizedBox(height: 16),
          for (final entry in data) ...[
            pw.Text(entry.vehicle.displayName,
                style: pw.TextStyle(
                    fontSize: 15, fontWeight: pw.FontWeight.bold)),
            pw.Text(
              'Odometer: ${NumberFormat.decimalPattern().format(entry.vehicle.odometerKm)} km'
              '${entry.vehicle.plateNumber != null ? ' · Plate: ${entry.vehicle.plateNumber}' : ''}',
              style: const pw.TextStyle(fontSize: 10),
            ),
            pw.SizedBox(height: 6),
            if (entry.history.isEmpty)
              pw.Text('No service records.',
                  style: const pw.TextStyle(
                      fontSize: 10, color: PdfColors.grey600))
            else
              pw.TableHelper.fromTextArray(
                headerStyle: pw.TextStyle(fontWeight: pw.FontWeight.bold),
                headerDecoration:
                    const pw.BoxDecoration(color: PdfColors.grey300),
                cellStyle: const pw.TextStyle(fontSize: 9),
                headers: const [
                  'Date',
                  'Service',
                  'Odometer',
                  'Garage',
                  'Cost',
                  'Notes'
                ],
                data: entry.history
                    .map((r) => [
                          df.format(r.date),
                          r.type.name,
                          NumberFormat.decimalPattern().format(r.odometerKm),
                          r.garageName ?? '-',
                          r.cost?.formatted() ?? '-',
                          r.notes ?? '-',
                        ])
                    .toList(),
              ),
            pw.SizedBox(height: 16),
          ],
          pw.Text('Generated by Siyyarte · ${df.format(DateTime.now())}',
              style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey600)),
        ],
      ),
    );

    await Printing.layoutPdf(onLayout: (format) => doc.save());
  }
}
